# script.py

def main():
    """
    Prints 'Hello, World!' to the console.
    """
    # Using triple quotes for a multiline string
    # This is the standard way to define a multiline string in Python
    message = """
Hello, World!
"""
    # Using print function with f-string for formatting
    # This is a more modern and efficient way to print strings
    print(f"{message}")

if __name__ == "__main__":
    main()